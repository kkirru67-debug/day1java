class Explicit{
    public static void main(String[]args){
        double dou = 10.2345;
        int val =(int)dou;
        int num = 50;
        char var =(char)num;
        float num1 = 3.14f;
        byte byt = (byte)num1;
        System.out.println(dou);
        System.out.println(val);
        System.out.println(num);
        System.out.println(var);
        System.out.println(num1);
        System.out.println(byt);
    }
}